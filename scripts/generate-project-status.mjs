import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const boardPath = path.join(root, 'docs', 'project-board.json');
const outPath = path.join(root, 'docs', 'generated', 'project-status.md');

function readBoard() {
  return JSON.parse(fs.readFileSync(boardPath, 'utf8'));
}

function countBy(items, key) {
  const out = new Map();
  for (const item of items) out.set(item[key], (out.get(item[key]) ?? 0) + 1);
  return [...out.entries()].sort((a, b) => String(a[0]).localeCompare(String(b[0])));
}

function esc(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
}

function main() {
  const board = readBoard();
  const tasks = [...board.tasks].sort((a, b) => a.order - b.order);
  const active = tasks.find((task) => task.status === 'in_progress')
    ?? tasks.find((task) => task.status === 'codex_verified')
    ?? tasks.find((task) => task.status === 'customer_validation')
    ?? null;
  const next = tasks.find((task) => task.status === 'planned') ?? null;
  const done = tasks.filter((task) => task.status === 'done').length;
  const lines = [];

  lines.push('# Generated pgstat Project Status');
  lines.push('');
  lines.push('Status: generated');
  lines.push('Source: docs/project-board.json');
  lines.push('');
  lines.push('Do not edit this file manually. Run:');
  lines.push('');
  lines.push('```text');
  lines.push('node scripts/generate-project-status.mjs');
  lines.push('```');
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push('| Metric | Value |');
  lines.push('| --- | ---: |');
  lines.push(`| Total tasks | ${tasks.length} |`);
  lines.push(`| Done tasks | ${done} |`);
  lines.push(`| Remaining tasks | ${tasks.length - done} |`);
  lines.push(`| Max in progress | ${board.project?.max_in_progress ?? 1} |`);
  lines.push('');
  lines.push('## Current Focus');
  lines.push('');
  if (active) {
    lines.push(`Current task: **${active.id} - ${esc(active.title)}**`);
    lines.push('');
    lines.push(`Status: \`${active.status}\``);
    lines.push('');
    lines.push(`Next action: ${esc(active.next_action)}`);
  } else {
    lines.push('Current task: none');
  }
  lines.push('');
  if (next) {
    lines.push(`Next planned task: **${next.id} - ${esc(next.title)}**`);
  } else {
    lines.push('Next planned task: none');
  }
  lines.push('');
  lines.push('## Status Counts');
  lines.push('');
  lines.push('| Status | Count |');
  lines.push('| --- | ---: |');
  for (const [status, count] of countBy(tasks, 'status')) lines.push(`| ${esc(status)} | ${count} |`);
  lines.push('');
  lines.push('## Workstream Counts');
  lines.push('');
  lines.push('| Workstream | Count |');
  lines.push('| --- | ---: |');
  for (const [workstream, count] of countBy(tasks, 'workstream')) lines.push(`| ${esc(workstream)} | ${count} |`);
  lines.push('');
  lines.push('## Task Board');
  lines.push('');
  lines.push('| Order | ID | Priority | Workstream | Status | Title | Next action |');
  lines.push('| ---: | --- | --- | --- | --- | --- | --- |');
  for (const task of tasks) {
    lines.push(`| ${task.order} | ${task.id} | ${task.priority} | ${esc(task.workstream)} | ${task.status} | ${esc(task.title)} | ${esc(task.next_action)} |`);
  }
  lines.push('');
  lines.push('## Dependency Map');
  lines.push('');
  lines.push('| ID | Depends on | Blocks |');
  lines.push('| --- | --- | --- |');
  for (const task of tasks) {
    const dependsOn = (task.dependencies ?? []).join(', ') || '-';
    const blocks = tasks.filter((candidate) => (candidate.dependencies ?? []).includes(task.id)).map((candidate) => candidate.id).join(', ') || '-';
    lines.push(`| ${task.id} | ${esc(dependsOn)} | ${esc(blocks)} |`);
  }
  lines.push('');
  lines.push('## Closure Rules');
  lines.push('');
  lines.push(`Automatic task close: **${board.closure_policy?.automatic_task_close ? 'yes' : 'no'}**`);
  lines.push('');
  lines.push(esc(board.closure_policy?.reason));
  lines.push('');
  lines.push('A task can move to `done` only when acceptance criteria, Codex verification evidence, and the customer acceptance gate satisfy docs/project-board.json.');
  lines.push('');

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');
  console.log('Generated docs/generated/project-status.md');
}

main();
